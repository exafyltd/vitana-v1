#!/usr/bin/env node
/**
 * VTID-05105 — desktop screen inventory for the Spotlight redesign
 * (docs/plans/desktop-spotlight, Phase 1a task 1a.1).
 *
 * Reads every <Route> in src/App.tsx (same extractor as the VTID-04502 screen
 * registry), drops redirects and the catch-all, and assigns each real screen a
 * TIER and an AREA by path prefix:
 *   A — member core (fully redesigned in Phases 2–4)
 *   B — member secondary (Phase 5)
 *   C — operator: admin / backoffice / dev / professional / staff (Phase 7)
 *   P — public / auth / legal / portal entry (Phase 7 leftovers)
 *
 * Writes docs/design-system/desktop-screen-inventory.md. Run:
 *   node scripts/design/desktop-screen-inventory.mjs [--check]
 * --check exits 1 when the committed file is out of date.
 * Archetypes per route are assigned in the screen manifest (Phase 1c).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { extractSpaRoutes } from '../nav/spa-routes.mjs';

const OUT = 'docs/design-system/desktop-screen-inventory.md';
const CATCH_ALL = new Set(['*', '/*']);

// First matching prefix wins; order matters (more specific first).
const RULES = [
  ['C', 'Admin', /^\/(admin|exafy-admin)(\/|$)/],
  ['C', 'Backoffice', /^\/backoffice(\/|$)/],
  ['C', 'Dev', /^\/dev(\/|$)/],
  ['C', 'Professional', /^\/professional(\/|$)/],
  ['C', 'Staff', /^\/staff(\/|$)/],
  ['A', 'News & posts', /^\/(home|news|post|dashboard)(\/|$)/],
  ['A', 'Community & social', /^\/(comm|community|u|e|live|media)(\/|$)/],
  ['A', 'Discover & marketplace', /^\/(discover|shop|cart|universal-cart|checkout|commerce|business)(\/|$)/],
  ['A', 'Messages', /^\/(inbox|messages)(\/|$)/],
  ['A', 'Profile', /^\/(me|profile)(\/|$)/],
  ['B', 'Health', /^\/(health|health-tracker|patient)(\/|$)/],
  ['B', 'Wallet', /^\/wallet(\/|$)/],
  ['B', 'AI & memory', /^\/(ai|assistant|memory|intents|autopilot)(\/|$)/],
  ['B', 'Settings', /^\/(settings|support|connectors)(\/|$)/],
  ['B', 'Calendar & reminders', /^\/(calendar|reminders)(\/|$)/],
  ['B', 'Sharing', /^\/sharing(\/|$)/],
  ['B', 'Other member screens', /^\/(daily-diary|my-tickets|search|partner|redeem|packages|tickets|creator|delete-account)(\/|$)/],
  ['P', 'Public, auth, legal & portals', /.*/],
];

export function classify(path) {
  for (const [tier, area, re] of RULES) if (re.test(path)) return { tier, area };
  return { tier: 'P', area: 'Public, auth, legal & portals' };
}

export function buildInventory(appSource) {
  const routes = extractSpaRoutes(appSource);
  const redirects = routes.filter((r) => r.redirectTo).length;
  const seen = new Set();
  const screens = [];
  for (const r of routes) {
    if (r.redirectTo || CATCH_ALL.has(r.path) || seen.has(r.path)) continue;
    seen.add(r.path);
    screens.push({ path: r.path, ...classify(r.path) });
  }
  screens.sort((a, b) => a.tier.localeCompare(b.tier) || a.area.localeCompare(b.area) || a.path.localeCompare(b.path));
  return { total: routes.length, redirects, screens };
}

const TIER_NAME = { A: 'A — member core', B: 'B — member secondary', C: 'C — operator', P: 'P — public / auth / legal / portals' };
const TIER_PHASE = { A: 'Phases 2–4', B: 'Phase 5', C: 'Phase 7 (VTID-05113…05116)', P: 'Phase 7 leftovers (VTID-05117)' };

export function render({ total, redirects, screens }) {
  const byTier = {};
  const byArea = {};
  for (const s of screens) {
    byTier[s.tier] = (byTier[s.tier] ?? 0) + 1;
    const k = `${s.tier}|${s.area}`;
    byArea[k] = (byArea[k] ?? 0) + 1;
  }
  const lines = [
    '# Desktop screen inventory — Spotlight (VTID-05105)',
    '',
    '> Generated by `node scripts/design/desktop-screen-inventory.mjs` from `src/App.tsx`. Do not edit by hand.',
    '> Plan: `docs/plans/desktop-spotlight/plan.md`. Archetypes per route live in the screen manifest (Phase 1c).',
    '',
    `- \`<Route>\` entries in App.tsx: **${total}**`,
    `- Redirects (\`<Navigate>\`), not screens: **${redirects}**`,
    `- Distinct screen routes (excluding redirects and the catch-all): **${screens.length}**`,
    '',
    '## By tier',
    '',
    '| Tier | Routes | Spotlight phase |',
    '|---|---|---|',
    ...['A', 'B', 'C', 'P'].map((t) => `| ${TIER_NAME[t]} | ${byTier[t] ?? 0} | ${TIER_PHASE[t]} |`),
    '',
    '## By area',
    '',
    '| Tier | Area | Routes |',
    '|---|---|---|',
    ...Object.entries(byArea)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([k, n]) => {
        const [t, area] = k.split('|');
        return `| ${t} | ${area} | ${n} |`;
      }),
    '',
    '## All screen routes',
    '',
    '| Route | Tier | Area |',
    '|---|---|---|',
    ...screens.map((s) => `| \`${s.path}\` | ${s.tier} | ${s.area} |`),
    '',
  ];
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const md = render(buildInventory(readFileSync('src/App.tsx', 'utf8')));
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== md) {
      console.error(`${OUT} is out of date — run node scripts/design/desktop-screen-inventory.mjs`);
      process.exit(1);
    }
    console.log(`${OUT} is up to date`);
  } else {
    writeFileSync(OUT, md);
    console.log(`wrote ${OUT}`);
  }
}
