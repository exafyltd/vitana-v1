const IMPORT_RE = /from\s+["'][^"']*_shared\/caller-auth(\.ts)?["']/;
const CALL_RE = /\b(requireUser|isServiceRoleCaller|isTriggerSecretCaller)\s*\(/;

export function satisfiesRule(src) {
  return IMPORT_RE.test(src) && CALL_RE.test(src);
}

export function check(dir) {
  const problems = [];
  const names = fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name !== '_shared' && !e.name.startsWith('.'))
    .map((e) => e.name)
    .filter((n) => fs.existsSync(path.join(dir, n, 'index.ts')));
  for (const name of names) {
    const ok = satisfiesRule(fs.readFileSync(path.join(dir, name, 'index.ts'), 'utf8'));
    if (Object.hasOwn(LEGACY, name)) {
      if (ok) problems.push(`${name}: migrated — remove ${name} from LEGACY`);
    } else if (!ok) {
      problems.push(`${name}: must import _shared/caller-auth and call requireUser / isServiceRoleCaller / isTriggerSecretCaller`);
    }
  }
  for (const name of Object.keys(LEGACY)) {
    if (!names.includes(name)) problems.push(`${name}: no folder — remove ${name} from LEGACY`);
  }
  return { checked: names.length, problems };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { checked, problems } = check(functionsDir);
  if (problems.length) {
    console.error(`check-edge-function-auth: ${problems.length} problem(s) (VTID-05442):`);
    for (const p of problems) console.error(`  ${p}`);
    process.exit(1);
  }
  console.log(`check-edge-function-auth: ok — ${checked} functions, ${Object.keys(LEGACY).length} legacy`);
}
