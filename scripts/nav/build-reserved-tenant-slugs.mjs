/**
 * VTID-05151 — reserved tenant slugs.
 *
 * A community portal lives at /<slug> (TenantPortal, the `/:tenantSlug`
 * route). React Router ranks static segments above dynamic ones, so a tenant
 * whose slug equals a static top-level route (/home, /discover, /commerce …)
 * could never be reached — the static page would always win. This script lists
 * every first path segment the app already owns:
 *
 *   - first segments of every <Route> in src/App.tsx (redirects included),
 *   - first segments of every route in the voice-navigation registry,
 *   - every top-level directory in public/ (served from the root),
 *   - platform prefixes that are not SPA routes (api, auth, rest, storage, …),
 *
 * minus LEGACY_TENANT_ROUTES — the two tenants that own a static route of
 * their own (/maxina, /alkalma).
 *
 * Output (sorted, no timestamp, so a fresh build equals the committed file):
 *   src/generated/reserved-tenant-slugs.json  — read by the app (isReservedSlug)
 *   public/reserved-tenant-slugs.json         — served at /reserved-tenant-slugs.json
 *                                               for provision_tenant's slug check
 *
 * Runs as `prebuild` next to build-nav-registry.mjs. A test
 * (src/lib/tenant-slug-reserved.test.ts) fails when the committed file is stale.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { extractSpaRoutes } from './spa-routes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_SRC = path.join(ROOT, 'src', 'generated', 'reserved-tenant-slugs.json');
const OUT_PUBLIC = path.join(ROOT, 'public', 'reserved-tenant-slugs.json');

/** Tenants that own a static top-level route; their slug is theirs, not reserved. */
export const LEGACY_TENANT_ROUTES = ['maxina', 'alkalma'];

/** Prefixes the platform answers itself (Supabase, gateway, asset paths, short links). */
export const PLATFORM_PREFIXES = ['api', 'auth', 'rest', 'storage', 'functions', '_intro', 'e', 'i', 'u', 'assets'];

/** First static segment of a route path, or null for `/`, `*` and dynamic segments. */
export function firstSegment(routePath) {
  const seg = String(routePath).split('?')[0].replace(/^\/+/, '').split('/')[0];
  if (!seg || seg === '*' || seg.startsWith(':')) return null;
  return seg.toLowerCase();
}

export function buildReservedSlugs({
  appSource = fs.readFileSync(path.join(ROOT, 'src', 'App.tsx'), 'utf8'),
  screensJson = fs.readFileSync(path.join(ROOT, 'src', 'navigation', 'registry', 'screens.json'), 'utf8'),
  publicEntries = fs.readdirSync(path.join(ROOT, 'public')),
} = {}) {
  const reserved = new Set(PLATFORM_PREFIXES);
  for (const r of extractSpaRoutes(appSource)) {
    const seg = firstSegment(r.path);
    if (seg) reserved.add(seg);
  }
  for (const s of JSON.parse(screensJson).screens) {
    for (const route of [s.route, s.mobileRoute]) {
      const seg = route ? firstSegment(route) : null;
      if (seg) reserved.add(seg);
    }
  }
  for (const entry of publicEntries) {
    // A slug never contains a dot, so only dot-free entries (directories) can
    // collide. Skipping files also keeps build outputs (nav-registry.json, this
    // file) from changing the result.
    if (entry.includes('.')) continue;
    reserved.add(entry.toLowerCase());
  }
  for (const legacy of LEGACY_TENANT_ROUTES) reserved.delete(legacy);
  return {
    _comment: 'VTID-05151 — generated by scripts/nav/build-reserved-tenant-slugs.mjs. Do not edit by hand.',
    legacy_tenant_routes: LEGACY_TENANT_ROUTES,
    reserved: [...reserved].sort(),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = `${JSON.stringify(buildReservedSlugs(), null, 2)}\n`;
  for (const file of [OUT_SRC, OUT_PUBLIC]) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, out);
  }
  console.log(`[reserved-tenant-slugs] ${JSON.parse(out).reserved.length} slugs → ${path.relative(ROOT, OUT_SRC)}, ${path.relative(ROOT, OUT_PUBLIC)}`);
}
