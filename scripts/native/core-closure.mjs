#!/usr/bin/env node
/**
 * VTID-05183 — the @vitana/core closure gate (Native app Wave 1 N1, plan change 6).
 *
 * packages/core reaches web code in two ways: re-export entry files
 * (packages/core/src/*.ts, `export … from '@/…'`) and the imports kept in the
 * generated extracts. This script computes the runtime closure of every src/
 * module core reaches, with the same import graph as extraction-deps.mjs, and
 *
 *   --write   writes packages/core/closure.generated.json (what the native
 *             resolver guard admits from src/) and
 *             scripts/native/mobile-ci-paths.generated.json (the exact src/
 *             paths that make NATIVE-CI run the full mobile job)
 *   --check   fails on: a closure module that is not class A (own or
 *             transitive), a production-host literal anywhere in packages/**,
 *             a re-export missing from packages/core/manifest.json (or a
 *             manifest line nothing re-exports), `@/` outside the entry files,
 *             a bare import apps/mobile does not depend on or a web-only
 *             package, or a stale generated file
 *   --md      regenerates the module map section of packages/core/README.md
 *             (a snapshot, never checked: it changes with unrelated web code)
 *   [--root <repo>]  fixture trees (tests)
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { analyze, resolveImport, prodHostsIn, isWebOnlyPackage, CANDIDATES, recommend } from './extraction-deps.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO = resolve(HERE, '../..');
export const CORE_SRC = 'packages/core/src';
export const MANIFEST = 'packages/core/manifest.json';
export const EXTRACT = 'packages/core/extract.json';
export const CLOSURE_OUT = 'packages/core/closure.generated.json';
export const CI_PATHS_OUT = 'scripts/native/mobile-ci-paths.generated.json';
export const TOKENS_CONFIG = 'packages/tokens/tokens.config.json';
export const README = 'packages/core/README.md';
const MD_BEGIN = '<!-- module-map:begin (generated by node scripts/native/core-closure.mjs --md) -->';
const MD_END = '<!-- module-map:end -->';
const ASSET_EXT = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.svg', '.ttf', '.otf', '.mp3', '.mp4', '.wav']);
const TEXT_EXT = new Set(['.ts', '.tsx', '.js', '.mjs', '.cjs', '.json', '.md']);
const CMD = 'node scripts/native/core-closure.mjs';

const posix = (p) => p.split(sep).join('/');

function walk(root, rel, out = []) {
  const dir = join(root, rel);
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir).sort()) {
    if (name === 'node_modules') continue;
    const r = `${rel}/${name}`;
    if (statSync(join(root, r)).isDirectory()) walk(root, r, out);
    else out.push(r);
  }
  return out;
}

/** Every module specifier in a file: imports, export-from and require()/import() calls. */
export function specifiersOf(text, file) {
  const kind = file.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, kind);
  const out = [];
  const visit = (n) => {
    if (ts.isImportDeclaration(n) && ts.isStringLiteral(n.moduleSpecifier)) {
      const c = n.importClause;
      const typeOnly = !!c && (c.isTypeOnly || (!c.name && c.namedBindings && ts.isNamedImports(c.namedBindings) && c.namedBindings.elements.length > 0 && c.namedBindings.elements.every((e) => e.isTypeOnly)));
      out.push({ spec: n.moduleSpecifier.text, typeOnly: !!typeOnly });
    } else if (ts.isExportDeclaration(n) && n.moduleSpecifier && ts.isStringLiteral(n.moduleSpecifier)) {
      const typeOnly = n.isTypeOnly || (n.exportClause && ts.isNamedExports(n.exportClause) && n.exportClause.elements.length > 0 && n.exportClause.elements.every((e) => e.isTypeOnly));
      out.push({ spec: n.moduleSpecifier.text, typeOnly: !!typeOnly });
    } else if (ts.isCallExpression(n) && n.arguments.length && ts.isStringLiteralLike(n.arguments[0])
      && (n.expression.kind === ts.SyntaxKind.ImportKeyword || (ts.isIdentifier(n.expression) && n.expression.text === 'require'))) {
      out.push({ spec: n.arguments[0].text, typeOnly: false });
    }
    n.forEachChild(visit);
  };
  visit(sf);
  return out;
}

const pkgName = (spec) => (spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0]);

/** Computes everything; never writes. */
export function compute(root = REPO, { analysis } = {}) {
  const errors = [];
  const modules = (analysis ?? analyze(root)).modules;
  const manifest = existsSync(join(root, MANIFEST)) ? JSON.parse(readFileSync(join(root, MANIFEST), 'utf8')) : { reexports: {} };
  const reexports = manifest.reexports ?? {};
  const mobilePkg = JSON.parse(readFileSync(join(root, 'apps/mobile/package.json'), 'utf8'));
  const mobileDeps = new Set([...Object.keys(mobilePkg.dependencies ?? {}), ...Object.keys(mobilePkg.devDependencies ?? {})]);

  const roots = new Map(); // src rel -> { from: [core files], typeOnly }
  const assets = new Set();
  const reexported = new Set();
  const coreFiles = walk(root, CORE_SRC).filter((f) => /\.(ts|tsx)$/.test(f));
  for (const file of coreFiles) {
    const isEntry = posix(dirname(file)) === CORE_SRC;
    const isExtract = file.endsWith('.generated.ts');
    for (const { spec, typeOnly } of specifiersOf(readFileSync(join(root, file), 'utf8'), file)) {
      if (spec.startsWith('.') && !resolve(join(root, dirname(file)), spec).startsWith(join(root, 'packages') + sep)) {
        // A relative path out of packages/ (the asset map, or a forbidden reach into src/).
        const r = resolveImport(root, file, spec);
        if (r.internal && ASSET_EXT.has(extname(r.internal).toLowerCase()) && isExtract) { assets.add(r.internal); continue; }
        errors.push(`${file}: relative import ${spec} leaves packages/ — reach web code only through '@/…' in an entry file`);
        continue;
      }
      if (spec.startsWith('.')) continue; // inside packages/
      if (spec.startsWith('@/')) {
        if (!isEntry && !isExtract) { errors.push(`${file}: imports ${spec}; only the entry files (${CORE_SRC}/*.ts) re-export web code`); continue; }
        const r = resolveImport(root, file, spec);
        if (!r.internal) { errors.push(`${file}: cannot resolve ${spec}`); continue; }
        if (isEntry) {
          reexported.add(r.internal);
          if (!reexports[r.internal]) errors.push(`${file}: re-exports ${r.internal} (${spec}), which is not listed in ${MANIFEST} — add a line with its reason and consumer lanes`);
        }
        const prev = roots.get(r.internal);
        roots.set(r.internal, { from: [...(prev?.from ?? []), file], typeOnly: (prev ? prev.typeOnly : true) && typeOnly });
        continue;
      }
      // Bare package.
      const name = pkgName(spec);
      if (isWebOnlyPackage(spec)) errors.push(`${file}: imports the web-only package ${spec}`);
      else if (!mobileDeps.has(name)) errors.push(`${file}: imports ${spec}, which apps/mobile/package.json does not depend on (core's packages resolve from apps/mobile/node_modules)`);
    }
  }
  for (const rel of Object.keys(reexports)) {
    if (!reexported.has(rel)) errors.push(`${MANIFEST} lists ${rel}, but no entry file re-exports it`);
    const m = reexports[rel];
    if (!m || !m.reason || !Array.isArray(m.lanes) || !m.lanes.length) errors.push(`${MANIFEST}: ${rel} needs "reason" and "lanes"`);
  }

  // Runtime closure over the analysis graph, with the shortest chain to a non-A module.
  const closure = new Set();
  const parent = new Map();
  const queue = [];
  for (const r of [...roots.keys()].sort()) {
    if (!modules[r]) {
      if (existsSync(join(root, r))) { closure.add(r); continue; } // a json leaf the analysis did not reach
      errors.push(`core reaches ${r}, which the extraction analysis does not know`);
      continue;
    }
    if (!closure.has(r)) { closure.add(r); parent.set(r, null); queue.push(r); }
  }
  while (queue.length) {
    const at = queue.shift();
    for (const d of modules[at].imports) if (!closure.has(d)) { closure.add(d); parent.set(d, at); queue.push(d); }
  }
  const chainTo = (rel) => { const c = []; for (let x = rel; x; x = parent.get(x)) c.unshift(x); return c; };
  for (const rel of [...closure].sort()) {
    const m = modules[rel];
    if (!m) continue;
    if (m.own !== 'A') {
      const sig = m.signals.slice(0, 3).map((s) => `${s.type} \`${s.detail}\` L${s.line}`).join('; ');
      errors.push(`${rel} is class ${m.own} (${sig}) and core reaches it: ${chainTo(rel).join(' → ')}`);
    }
  }
  for (const a of assets) if (!existsSync(join(root, a))) errors.push(`asset ${a} does not exist`);

  // No production host literal anywhere in packages/**.
  for (const file of walk(root, 'packages')) {
    if (!TEXT_EXT.has(extname(file))) continue;
    const hosts = prodHostsIn(readFileSync(join(root, file), 'utf8'));
    if (hosts.length) errors.push(`${file}: contains a production/staging host (${hosts.join(', ')}) — prod-fallback; core takes every endpoint from configuration`);
  }

  const files = [...closure].sort();
  const closureJson = {
    _generated: `AUTO-GENERATED by ${CMD} --write (VTID-05183). Do not edit. The src/ files @vitana/core reaches; apps/mobile/resolution.js admits these (and nothing else under src/ except the i18n catalog shards).`,
    files,
    assets: [...assets].sort(),
  };
  const extract = existsSync(join(root, EXTRACT)) ? JSON.parse(readFileSync(join(root, EXTRACT), 'utf8')) : { entries: {} };
  const extractSources = Object.values(extract.entries ?? {}).flatMap((e) => (e.sources ?? []).map((s) => s.file));
  const tokens = existsSync(join(root, TOKENS_CONFIG)) ? JSON.parse(readFileSync(join(root, TOKENS_CONFIG), 'utf8')) : {};
  const tokenSources = [tokens.css, tokens.tailwind].filter(Boolean);
  const ciPaths = {
    _generated: `AUTO-GENERATED by ${CMD} --write (VTID-05183). Do not edit. A change to any of these paths runs the full NATIVE-CI mobile job (besides apps/mobile/**, packages/** and the workflow itself).`,
    paths: [...new Set([...files, ...assets, ...extractSources, ...tokenSources])].sort(),
  };
  return {
    errors,
    roots,
    outputs: {
      [CLOSURE_OUT]: `${JSON.stringify(closureJson, null, 2)}\n`,
      [CI_PATHS_OUT]: `${JSON.stringify(ciPaths, null, 2)}\n`,
    },
    modules,
    manifest,
    extract,
    closure: files,
    assets: closureJson.assets,
  };
}

export function staleOutputs(root, outputs) {
  return Object.entries(outputs).filter(([rel, text]) => !existsSync(join(root, rel)) || readFileSync(join(root, rel), 'utf8') !== text).map(([rel]) => rel);
}

export function moduleMap(r) {
  const L = [];
  L.push(MD_BEGIN, '');
  L.push('### Re-exported (transitively class A)', '');
  L.push('| module | entry | consumer lanes | reason |', '|---|---|---|---|');
  for (const [rel, m] of Object.entries(r.manifest.reexports ?? {}).sort()) {
    L.push(`| \`${rel}\` | \`@vitana/core/${m.entry.replace(/\.ts$/, '')}\` | ${m.lanes.join(', ')} | ${m.reason} |`);
  }
  L.push('', '### Extracted (generated from the web source, `extract.json`)', '');
  L.push('| entry | source | declarations |', '|---|---|---|');
  for (const [entry, e] of Object.entries(r.extract.entries ?? {})) {
    for (const s of e.sources ?? []) {
      const names = (s.take ?? []).map((t) => (typeof t === 'string' ? t : `${t.name} as ${t.as}`)).join(', ');
      L.push(`| \`${entry}\` | \`${s.file}\` | ${names}${s.stubs ? ` (stub: ${Object.keys(s.stubs).join(', ')})` : ''} |`);
    }
  }
  L.push('', `Runtime closure: **${r.closure.length}** \`src/\` files and **${r.assets.length}** assets (\`closure.generated.json\`).`, '');
  L.push('### Program §3 candidates not in core', '');
  L.push('| module | own / transitive | blocking signal | the move that unblocks it |', '|---|---|---|---|');
  for (const c of CANDIDATES) {
    if (r.closure.includes(c.path)) continue;
    const m = r.modules[c.path];
    if (!m) { L.push(`| \`${c.path}\` | — | not found | — |`); continue; }
    // A production host is never written into packages/** (the --check below would refuse it).
    const sig = [...new Set(m.signals.map((s) => (s.type === 'prod-fallback' ? 'prod-fallback (a production host literal)' : `${s.type} \`${s.detail}\``)))].slice(0, 2).join('; ') || '—';
    L.push(`| \`${c.path}\` (${c.note}) | ${m.own} / ${m.class} | ${sig} | ${recommend(r.modules, c.path)} |`);
  }
  L.push('', MD_END);
  return L.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const i = args.indexOf('--root');
  const root = i >= 0 ? resolve(args[i + 1]) : REPO;
  const r = compute(root);
  if (r.errors.length) {
    console.error(`core-closure: ${r.errors.length} problem(s):\n- ${r.errors.join('\n- ')}`);
    process.exit(1);
  }
  if (args.includes('--write')) for (const [rel, text] of Object.entries(r.outputs)) writeFileSync(join(root, rel), text);
  if (args.includes('--md')) {
    const path = join(root, README);
    const text = readFileSync(path, 'utf8');
    const a = text.indexOf(MD_BEGIN);
    const b = text.indexOf(MD_END);
    if (a < 0 || b < 0) { console.error(`core-closure: ${README} has no module-map markers`); process.exit(1); }
    writeFileSync(path, text.slice(0, a) + moduleMap(r) + text.slice(b + MD_END.length));
  }
  if (args.includes('--check')) {
    const stale = staleOutputs(root, r.outputs);
    if (stale.length) {
      console.error(`core-closure: out of date: ${stale.join(', ')}\nRun \`${CMD} --write\` and commit the result.`);
      process.exit(1);
    }
  }
  console.log(`core-closure: ${r.roots.size} roots, ${r.closure.length} src files, ${r.assets.length} assets — ${args.includes('--check') ? 'up to date' : 'ok'}`);
}
