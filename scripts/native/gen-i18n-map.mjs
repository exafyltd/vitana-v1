#!/usr/bin/env node
/**
 * VTID-05157 — native i18n catalog map (Native app Wave 0, plan change 6).
 *
 * Metro has no `import.meta.glob`, so the native app cannot discover the web
 * app's i18n shards at bundle time the way src/i18n/index.ts does. This script
 * writes a static `require()` map of every shard in src/i18n/<locale>/*.json
 * (skipping `_audit.json`, exactly like the web loader) to
 *
 *   apps/mobile/src/i18n/catalog-map.generated.ts
 *
 * The file is generated before typecheck/test/bundle (the `pre*` scripts in
 * apps/mobile/package.json) and is gitignored, so it is never committed, can
 * never conflict and needs no freshness check. Output order is sorted, so the
 * same tree always produces the same bytes.
 *
 *   node scripts/native/gen-i18n-map.mjs [--i18n-dir <dir>] [--out <file>]
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../..');

export const DEFAULT_I18N_DIR = join(REPO, 'src/i18n');
export const DEFAULT_OUT = join(REPO, 'apps/mobile/src/i18n/catalog-map.generated.ts');

/** Same rule as the web loader (src/i18n/index.ts isShard): audit reports are not translations. */
export function isShard(file) {
  return file.endsWith('.json') && !file.endsWith('_audit.json');
}

/** { locale: [shard file names, sorted] } for every locale directory that holds shards. */
export function listShards(i18nDir) {
  const out = {};
  for (const entry of readdirSync(i18nDir).sort()) {
    const dir = join(i18nDir, entry);
    if (!statSync(dir).isDirectory()) continue;
    const files = readdirSync(dir).filter(isShard).sort();
    if (files.length) out[entry] = files;
  }
  return out;
}

function posix(p) {
  return p.split(sep).join('/');
}

export function renderMap(shards, i18nDir, outFile) {
  let rel = posix(relative(dirname(outFile), i18nDir));
  if (!rel.startsWith('.')) rel = `./${rel}`;
  const lines = [
    '// AUTO-GENERATED by scripts/native/gen-i18n-map.mjs (VTID-05157). Do not edit.',
    '// Not committed (apps/mobile/.gitignore): regenerated by `npm run gen:i18n`,',
    '// which typecheck, test and bundle run first.',
    '/* eslint-disable */',
    '',
    'export type Shard = Record<string, unknown>;',
    '',
    '/** Shard file names per locale, in load order (sorted, `_audit.json` excluded). */',
    'export const SHARD_FILES: Record<string, readonly string[]> = {',
  ];
  for (const [locale, files] of Object.entries(shards)) {
    lines.push(`  ${JSON.stringify(locale)}: [`);
    for (const f of files) lines.push(`    ${JSON.stringify(f)},`);
    lines.push('  ],');
  }
  lines.push('};', '', '/** The shards themselves, statically required so Metro can bundle them. */');
  lines.push('export const SHARDS: Record<string, readonly Shard[]> = {');
  for (const [locale, files] of Object.entries(shards)) {
    lines.push(`  ${JSON.stringify(locale)}: [`);
    for (const f of files) lines.push(`    require(${JSON.stringify(`${rel}/${locale}/${f}`)}),`);
    lines.push('  ],');
  }
  lines.push('};', '');
  return lines.join('\n');
}

export function generate({ i18nDir = DEFAULT_I18N_DIR, out = DEFAULT_OUT } = {}) {
  const shards = listShards(i18nDir);
  if (Object.keys(shards).length === 0) throw new Error(`gen-i18n-map: no locale shards under ${i18nDir}`);
  const text = renderMap(shards, i18nDir, out);
  mkdirSync(dirname(out), { recursive: true });
  const before = existsSync(out) ? readFileSync(out, 'utf8') : null;
  if (before !== text) writeFileSync(out, text);
  return { out, locales: Object.keys(shards), files: Object.values(shards).reduce((n, f) => n + f.length, 0), changed: before !== text };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const opt = (name) => {
    const i = args.indexOf(`--${name}`);
    return i >= 0 ? resolve(args[i + 1]) : undefined;
  };
  const r = generate({ i18nDir: opt('i18n-dir') ?? DEFAULT_I18N_DIR, out: opt('out') ?? DEFAULT_OUT });
  console.log(`gen-i18n-map: ${r.locales.length} locales, ${r.files} shards → ${posix(relative(process.cwd(), r.out))}${r.changed ? '' : ' (unchanged)'}`);
}
